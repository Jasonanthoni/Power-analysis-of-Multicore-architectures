#!/usr/bin/env python3
import json, re

import os
import sys

if len(sys.argv) != 2:
    print("Usage:")
    print("python3 gen_mcpat_xml.py <benchmark_directory>")
    sys.exit(1)

benchmark_dir = sys.argv[1]

config_file = os.path.join(benchmark_dir, "config.json")
stats_file = os.path.join(benchmark_dir, "stats.txt")
output_xml = os.path.join(benchmark_dir, "mcpat_input.xml")


with open(config_file) as f:
    cfg = json.load(f)

stats = {}
pat = re.compile(r'^([\w.:]+)\s+([\S]+)')
with open(stats_file) as f:
    for line in f:
        line = line.strip()
        if not line or line.startswith('-'): continue
        m = pat.match(line)
        if not m: continue
        try: stats[m.group(1)] = float(m.group(2))
        except: stats[m.group(1)] = 0.0

def gs(k, d=0):
    v = stats.get(k, d)
    if v != v or v == float('inf'): return d
    return v

board      = cfg['board']
ruby       = board['cache_hierarchy']['ruby_system']
switch     = board['processor']['switch']
num_cores  = len(switch)
clock_tick = board['clk_domain']['clock'][0]
freq_mhz   = int(round(1e12 / clock_tick / 1e6))

l1         = ruby['l1_controllers'][0]
l1d_size   = l1['L1Dcache']['size']
l1d_assoc  = l1['L1Dcache']['assoc']
