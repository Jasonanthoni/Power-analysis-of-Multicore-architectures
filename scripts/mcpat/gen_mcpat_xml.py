branch_mispred = int(gs(f"{cp}.branchPred.condIncorrect", num_branches//10))

l1i_hits   = int(gs("board.cache_hierarchy.ruby_system.l1_controllers0.L1Icache.m_demand_hits", itlb_acc))
l1i_misses = int(gs("board.cache_hierarchy.ruby_system.l1_controllers0.L1Icache.m_demand_misses", itlb_miss))
l1d_hits   = int(gs("board.cache_hierarchy.ruby_system.l1_controllers0.L1Dcache.m_demand_hits", dtlb_rd+dtlb_wr))
l1d_misses = int(gs("board.cache_hierarchy.ruby_system.l1_controllers0.L1Dcache.m_demand_misses", dtlb_rd_miss+dtlb_wr_miss))
mem_reads  = int(gs("board.memory.mem_ctrl0.dram.readReqs", l1d_misses//2))
mem_writes = int(gs("board.memory.mem_ctrl0.dram.writeReqs", l1d_misses//4))

