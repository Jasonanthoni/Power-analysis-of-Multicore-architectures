l1i_size   = l1['L1Icache']['size']
l1i_assoc  = l1['L1Icache']['assoc']
l1i_lat    = l1['L1Icache'].get('dataAccessLatency', 2)
l1_tbes    = l1.get('number_of_TBEs', 256)
block_sz   = ruby.get('block_size_bytes', 64)

l2         = ruby['l2_controllers'][0]
l2_size    = l2['L2cache']['size']
l2_assoc   = l2['L2cache']['assoc']
l2_lat     = l2['L2cache'].get('dataAccessLatency', 10)
num_l2s    = len(ruby['l2_controllers'])

mc         = board['memory']['mem_ctrl'][0]['dram']
ranks      = mc.get('ranks_per_channel', 2)

cp = "board.processor.switch1.core"
total_cycles   = int(gs(f"{cp}.numCycles"))
total_insts    = int(gs(f"{cp}.commitStats0.numInsts"))
num_loads      = int(gs(f"{cp}.executeStats0.numLoadInsts"))
num_stores     = int(gs(f"{cp}.executeStats0.numStoreInsts"))
num_branches   = int(gs(f"{cp}.executeStats0.numBranches"))
int_alu        = int(gs(f"{cp}.executeStats0.numIntAluAccesses"))
fp_alu         = int(gs(f"{cp}.executeStats0.numFpAluAccesses"))
int_reg_reads  = int(gs(f"{cp}.executeStats0.numIntRegReads"))
int_reg_writes = int(gs(f"{cp}.executeStats0.numIntRegWrites"))
fp_reg_reads   = int(gs(f"{cp}.executeStats0.numFpRegReads"))
fp_reg_writes  = int(gs(f"{cp}.executeStats0.numFpRegWrites"))
itlb_acc       = int(gs(f"{cp}.mmu.itb.exAccesses"))
itlb_miss      = int(gs(f"{cp}.mmu.itb.exMisses"))
dtlb_rd        = int(gs(f"{cp}.mmu.dtb.rdAccesses"))
dtlb_wr        = int(gs(f"{cp}.mmu.dtb.wrAccesses"))
dtlb_rd_miss   = int(gs(f"{cp}.mmu.dtb.rdMisses"))
dtlb_wr_miss   = int(gs(f"{cp}.mmu.dtb.wrMisses"))
